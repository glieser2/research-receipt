import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const file = 'artifacts/bradbury/v3-e2e-input.json';
const planFile = 'docs/evidence/v3-validation-plan.json';
const raw = await readFile(file, 'utf8');
const plan = JSON.parse(await readFile(planFile, 'utf8'));
if (createHash('sha256').update(raw).digest('hex') !== plan.fixtureSha256 || plan.expected.length !== 4) throw new Error('Only extend the original unexecuted four-case plan once.');
const input = JSON.parse(raw);
const base = ['SUPPORTED', 'SCOPED_UNKNOWN', 'SCOPED_UNKNOWN', 'SUPPORTED'];
const add = (id, criterionId, statement, status) => {
  const submission = structuredClone(input.positive);
  const row = submission.claims.find(c => c.criterion_id === criterionId);
  row.statement = statement;
  if (criterionId === 'permissions') row.evidence_indices = [0];
  submission.report_body = submission.claims.map(c => c.statement).join('\n');
  submission.report_title = '预锁语义负例 · ' + id;
  input[id] = submission;
  const index = submission.claims.findIndex(c => c.criterion_id === criterionId);
  const statuses = [...base]; statuses[index] = status;
  const delivery = Array(4).fill('FULFILLED'); delivery[index] = status === 'CONTRADICTED' ? 'CONTRADICTED' : 'INSUFFICIENT';
  plan.expected.push({ id, spec: 'spec', submission: id, statuses, delivery, verdict: status === 'CONTRADICTED' ? 'NOT_ACCEPTED' : 'INSUFFICIENT_EVIDENCE', initialValidation: 'local semantic/guard tests; not automatically sent to a model' });
};
add('contradictionWithUnknown', 'permissions', input.negative.claims[0].statement + '其余权限未知。', 'CONTRADICTED');
add('falseCaution', 'permissions', '本次提交的Ownable源码没有显示transferOwnership是否带onlyOwner修饰符；这一点未知。', 'CONTRADICTED');
add('unsupportedPromise', 'withdrawals', '一个未提供源码或部署地址、使用Ownable的外部协议可保证用户随时即时提现。', 'NOT_ESTABLISHED');
add('unknownWithPromise', 'withdrawals', '一个未提供源码或部署地址、使用Ownable的外部协议的提现机制未知，因此该外部协议的用户能够随时即时退出。', 'NOT_ESTABLISHED');
add('deploymentOverreach', 'permissions', '截至2026-11-05，地址0x1111111111111111111111111111111111111111上的部署实例owner()返回0x2222222222222222222222222222222222222222；这两份源码证明了该当日链状态。', 'NOT_ESTABLISHED');
add('irrelevantTruth', 'permissions', '本次提交的源文件名为Ownable.sol。', 'NOT_ESTABLISHED');
input.missingClaim = structuredClone(input.positive);
input.missingClaim.claims = input.missingClaim.claims.filter(c => c.criterion_id !== 'permissions');
plan.expected.push({ id: 'missingClaim', spec: 'spec', submission: 'missingClaim', statuses: ['NOT_ESTABLISHED', ...base.slice(1)], delivery: ['INSUFFICIENT', 'FULFILLED', 'FULFILLED', 'FULFILLED'], verdict: 'INSUFFICIENT_EVIDENCE', omittedCriterionModelCalls: 0, initialValidation: 'local guard test' });
plan.guardExpectations = ['Missing/invalid evidence_requirement rejects order', 'Model-supplied delivery_status or SOURCE_UNAVAILABLE rejected', 'Format repair bounded globally to one request', 'False supported or false conservative leader classification rejected by independent comparison', 'Forged delivery, duplicate/missing finding, invalid references or source proof rejected', 'Optional contradiction cannot produce ACCEPTED'];
const updated = JSON.stringify(input, null, 2) + '\n';
plan.fixtureSha256 = createHash('sha256').update(updated).digest('hex');
plan.extendedBeforeExecutionAt = new Date().toISOString();
await writeFile(file, updated);
await writeFile(planFile, JSON.stringify(plan, null, 2) + '\n');
console.log(JSON.stringify({ expectedCases: plan.expected.length, fixtureSha256: plan.fixtureSha256 }));
